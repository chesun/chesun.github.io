#!/usr/bin/env python3
"""Generate web-sized gallery images and _data/photo_dims.yml.

Resizes every photo under the trip directories listed below into
assets/photos/web/ (1400px long edge, JPEG quality 78) and records each
copy's pixel dimensions in _data/photo_dims.yml, which
_includes/photo_rows.liquid uses to lay out the justified-rows galleries.

The order of entries in _data/photo_dims.yml is the display order. This
script preserves the existing order for photos already listed and appends
new photos at the end of their gallery. To curate the order visually, run
bin/curate.py.

Run from the repo root after adding photos:  python3 bin/generate_gallery.py
Requires Pillow (pip install Pillow).
"""

import glob
import os
import re

from PIL import Image, ImageOps

TRIP_DIRS = [
    "assets/photos/desolation/winter_2025",
    "assets/photos/sequoia/nov_2024",
    "assets/photos/zion/dec_2024/kolob",
    "assets/photos/zion/dec_2024/watchman",
]
MAX_EDGE = 1400
QUALITY = 78
DIMS_FILE = "_data/photo_dims.yml"


def read_existing_order():
    if not os.path.exists(DIMS_FILE):
        return []
    return re.findall(r'^"([^"]+)":', open(DIMS_FILE).read(), re.M)


existing_order = read_existing_order()
generated = {}
for d in TRIP_DIRS:
    out_dir = d.replace("assets/photos/", "assets/photos/web/")
    os.makedirs(out_dir, exist_ok=True)
    for f in sorted(glob.glob(d + "/*")):
        if not f.lower().endswith((".jpg", ".jpeg", ".png")):
            continue
        base = os.path.splitext(os.path.basename(f))[0] + ".jpg"
        out = os.path.join(out_dir, base)
        if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(f):
            im = Image.open(out)
        else:
            im = ImageOps.exif_transpose(Image.open(f)).convert("RGB")
            im.thumbnail((MAX_EDGE, MAX_EDGE), Image.LANCZOS)
            im.save(out, "JPEG", quality=QUALITY, optimize=True, progressive=True)
        generated["/" + out] = (im.width, im.height)

# existing curated order first (skipping photos that no longer exist), new photos after
ordered = [p for p in existing_order if p in generated]
ordered += [p for p in generated if p not in ordered]

with open(DIMS_FILE, "w") as fh:
    fh.write("# Generated by bin/generate_gallery.py — entry order is display order.\n")
    fh.write("# Reorder visually with bin/curate.py.\n")
    for path in ordered:
        w, h = generated[path]
        fh.write(f'"{path}":\n  w: {w}\n  h: {h}\n')

print(f"{len(ordered)} images written")
